/**
 * Emits a version-3 source map for every CSS asset a Vite build produces.
 *
 * Why this exists: the Webflow Marketplace submission form requires source maps for every minified
 * or generated production file, and App Review Preflight (2026-09-14, "Generated code is not
 * traceable to readable source") checks the stylesheet too — `styles.css` had no matching
 * `styles.css.map` while every JS chunk did. Vite 8 only produces JS maps (`build.sourcemap` is
 * ignored for the bundled CSS asset; verified empirically with `vite build --sourcemap`), so the
 * stylesheet map has to come from the build step that actually minifies it.
 *
 * How: the app config sets `build.cssMinify: false` so Vite (and the Tailwind plugin, which reads
 * that flag) hand over the readable, unminified stylesheet. In `generateBundle` — after Vite's own
 * css-post plugin has emitted the asset — this plugin minifies it with lightningcss (the same
 * minifier Vite 8 uses by default, with the same baseline browser targets) and writes the map it
 * produces next to it as `<name>.map`. No `sourceMappingURL` comment is appended: the shipped
 * bundle never references a map (`sourcemap: "hidden"` semantics — scripts/build-cli.mjs moves every
 * `*.map` under dist/ into the private submission-form zip before `webflow extension bundle`).
 *
 * The map's single source is the readable stylesheet the build produced, embedded as
 * `sourcesContent`, so the minified file is traceable to readable CSS generated by the exact build
 * that produced it.
 */

import { transform } from "lightningcss";

/**
 * lightningcss version encoding (`major << 16 | minor << 8 | patch`) of Vite 8's
 * `ESBUILD_BASELINE_WIDELY_AVAILABLE_TARGET` (chrome111, edge111, firefox114, safari16.4, ios16.4) —
 * the targets Vite's own `cssMinify: "lightningcss"` path derives from `build.cssTarget`'s default.
 * Kept in step by hand: a Vite upgrade that raises the baseline should update this list too.
 */
export const BASELINE_LIGHTNINGCSS_TARGETS = Object.freeze({
  chrome: 111 << 16,
  edge: 111 << 16,
  firefox: 114 << 16,
  safari: (16 << 16) | (4 << 8),
  ios_saf: (16 << 16) | (4 << 8),
});

const encoder = new TextEncoder();
const decoder = new TextDecoder();

/**
 * Minifies a readable stylesheet and returns the minified text plus its version-3 source map.
 * Pure: exported so the release-gate tests can prove the map shape without running a build.
 *
 * @param {{ fileName: string; code: string; targets?: Record<string, number> }} input
 * @returns {{ code: string; map: { version: 3; sources: string[]; sourcesContent: string[]; mappings: string; names: string[] } }}
 */
export function minifyCssWithSourceMap({ fileName, code, targets = BASELINE_LIGHTNINGCSS_TARGETS }) {
  const result = transform({
    filename: fileName,
    code: encoder.encode(code),
    minify: true,
    sourceMap: true,
    targets,
  });
  const minified = decoder.decode(result.code);
  if (!result.map) {
    throw new Error(`[css-sourcemap] lightningcss produced no source map for ${fileName}`);
  }
  const parsed = JSON.parse(decoder.decode(result.map));
  if (parsed.version !== 3 || typeof parsed.mappings !== "string" || !Array.isArray(parsed.sources)) {
    throw new Error(`[css-sourcemap] unexpected source map shape for ${fileName}`);
  }
  // The source is the readable stylesheet this build produced; embed it so the map stands alone
  // (the submission form receives the map zip without the unminified file).
  const map = {
    version: 3,
    file: fileName,
    sources: parsed.sources.length > 0 ? parsed.sources : [fileName],
    sourcesContent: [code],
    names: Array.isArray(parsed.names) ? parsed.names : [],
    mappings: parsed.mappings,
  };
  if (minified.includes("sourceMappingURL")) {
    throw new Error(`[css-sourcemap] minified ${fileName} references a source map; the bundle must not`);
  }
  return { code: minified, map };
}

/**
 * Vite plugin. Requires `build.cssMinify: false` in the consuming config — with Vite minifying the
 * asset first there is no readable text left to map to, so the plugin refuses to run otherwise.
 */
export function createCssSourceMapPlugin() {
  /** @type {boolean} */
  let cssMinifyDisabled = false;
  return {
    name: "codalyn:css-sourcemap",
    apply: "build",
    enforce: "post",
    configResolved(config) {
      cssMinifyDisabled = config.build.cssMinify === false;
    },
    generateBundle(_options, bundle) {
      const cssAssets = Object.values(bundle).filter(
        (entry) => entry.type === "asset" && entry.fileName.endsWith(".css")
      );
      if (cssAssets.length === 0) {
        return;
      }
      if (!cssMinifyDisabled) {
        throw new Error(
          "[css-sourcemap] set build.cssMinify to false — the plugin minifies each stylesheet itself so it can " +
            "emit the source map Vite does not produce for CSS"
        );
      }
      for (const asset of cssAssets) {
        const readable = typeof asset.source === "string" ? asset.source : decoder.decode(asset.source);
        const { code, map } = minifyCssWithSourceMap({ fileName: asset.fileName, code: readable });
        asset.source = code;
        this.emitFile({ type: "asset", fileName: `${asset.fileName}.map`, source: JSON.stringify(map) });
      }
    },
  };
}
